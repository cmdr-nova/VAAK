 let plain=current_plain(n,f);
 let mut spoiler=if card::boolean(obj,"summary"){
  card::php_trim(&crate::home_hydrate_ranked::html_entity_decode(&static_regex!(r"(?s)<[^>]*>").replace_all(string(obj,"summary"),""))).to_owned()
 }else{String::new()};
