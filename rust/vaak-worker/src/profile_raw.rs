//! Exact raw-outbox dialect of ap-admin.php::admin_render_outbox_card.
//! This painter never normalizes an outbox row into a fabricated Mastodon row.
//! Admission, current SQL facts and recursive quote grants belong to the
//! private profile context; this module performs no database or network IO.
// Immutable compiled patterns only; request text, source facts and results
// remain uncached. Each callsite retains exactly its original regex literal.
macro_rules! static_regex { ($pattern:literal) => {{
 static REGEX: std::sync::OnceLock<regex::Regex> = std::sync::OnceLock::new();
 REGEX.get_or_init(||{
  #[cfg(test)] { crate::library::note_static_regex_compile(); }
  regex::Regex::new($pattern).unwrap()
 })
 }}; }

