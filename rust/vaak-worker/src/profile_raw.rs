fn raw_media(obj:&Value,f:&RawProfileFacts)->Vec<Value>{
 let mut media=Vec::new();let atts=obj.get("attachment");
 let list=match atts{Some(Value::Array(a))=>a.clone(),Some(a)if a.get("type").is_some_and(|v|!v.is_null())=>vec![a.clone()],_=>vec![]};
 for att in list{
  let url=att.get("url").and_then(Value::as_str).or_else(||att.get("url").and_then(|v|v.get("href")).and_then(Value::as_str)).unwrap_or("");
  let mt=string(&att,"mediaType").to_ascii_lowercase();let kind=string(&att,"type");
  let video=static_regex!(r"(?i)\.(mp4|webm|mov|m4v|m3u8)(?:[?#].*)?$").is_match(url);
  if url.starts_with("https://")&&(mt.starts_with("image/")||mt.starts_with("video/")||mt.starts_with("audio/")||matches!(kind,"Image"|"Video"|"Audio")||matches!(mt.as_str(),"application/x-mpegurl"|"application/vnd.apple.mpegurl")||video){media.push(json!({"url":url,"mediaType":if mt.is_empty(){Value::Null}else{Value::String(mt)},"preview_url":f.media_preview_by_url.get(url).cloned().unwrap_or_default()}));}
 }
 media
}
pub(crate) fn root_preview_allowed(raw:&Value,f:&RawProfileFacts)->bool{
 let decoded:Value=serde_json::from_str(string(raw,"raw_create_json")).unwrap_or(Value::Null);
 let obj=decoded.get("object").unwrap_or(&decoded);
 let media=card::media_row(&raw_media(obj,f),f.card.lazy_media);
 let fallback=if f.card.poll_row.is_none(){raw_poll_fallback(obj)}else{None};
 let poll=f.card.poll_row.as_ref().or(fallback.as_ref()).map(|r|card::poll_html_mode(r,string(raw,"id").trim_end_matches('/'),&f.card,f.guest)).unwrap_or_default();
 media.is_empty()&&poll.is_empty()&&!current_plain(raw,f).is_empty()
}

